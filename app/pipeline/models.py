import torch 
import torch.nn as nn 

from collections import OrderedDict
from sklearn.cluster import KMeans 

class SLP(nn.Module): 
    def __init__(self, input_size, output_size ): 
        super().__init__()
        self.layer = nn.Linear(input_size, output_size)


    def forward(self, data): 
        res = self.layer(data)
        return res  


class FNN(nn.Module): 
    def __init__(self, input_size, hidden_sizes, output_size): 
        super().__init__()
        self.layers= nn.Sequential()

        self.layers.append(nn.Linear(input_size, hidden_sizes[0]))
        self.layers.append(nn.ReLU())
        # self.layers.append(nn.Dropout(p=0.3)) 
        for i in range(len(hidden_sizes)-1): 
            self.layers.append(nn.Linear(hidden_sizes[i], hidden_sizes[i+1]))
            self.layers.append(nn.ReLU())
            # self.layers.append(nn.Dropout(p=0.3))

        # last hidden layer to output 
        self.layers.append(nn.Linear(hidden_sizes[-1], output_size))


    def forward(self, data): 
        res = self.layers(data)
        return res 



class KMeansFNN(nn.Module): 
    '''this combines the kmeans and fnn model'''
    def __init__(self, k_value, adjusted_input_size, hidden_sizes, output_size):
        '''
        input size adjusted for the cluster labels
        ''' 
        super().__init__()

        self.kmeans = KMeans(n_clusters=k_value, random_state= 1 )

        self.fnn = FNN(adjusted_input_size, hidden_sizes, output_size)
    
    def train_kmeans(self, fulldata) -> None : # full x train data 
        self.kmeans.fit(fulldata)
        return 
    
    def forward(self, data): 
        # get clusterlabels from trained kmeans model 
        labels = self.kmeans.predict(data)
        labels =torch.unsqueeze (torch.from_numpy(labels), dim = 1 )

        # concatenate to data 
        data= torch.cat([data, labels], dim = 1 )
        # self.logger.debug( 'ERASE LATER, concatenated array is on device ' + data.device)
        
        # apply fnn 
        res= self.fnn(data) 
        return res 

class Autoencoder(nn.Module): 
    '''
    autoencoder model class 
    '''
    def __init__(self, input_size): 
        super().__init__()
        self.embedding_size = 4 

        # encoder 
        encoder_layers = OrderedDict([
            ('layer1', nn.Linear(input_size, 32)) , 
            ('layer 2', nn.Linear(32, 16)), 
            ('layer 3', nn.Linear(16, self.embedding_size))
        ])
        self.encoder = nn.Sequential(encoder_layers)

        # decoder 
        self.decoder= nn.Sequential(
            nn.Linear(self.embedding_size, 16), 
            nn.Linear(16, 32), 
            nn.Linear(32, input_size)
        )

    def forward(self, data): 
        ''' for train loop '''
        embedding = self.encoder(data)
        reconstructed = self.decoder(embedding)

        return reconstructed 
    
    def predict_embedding(self, data): 
        embedding = self.encoder(data)
        return embedding 
    

class AutoencoderKmeansFNN(nn.Module): 
    '''
    this calls on autoencoder model and kmeans+FNN model
    '''
    def __init__(self, k_value, input_size, hidden_sizes, output_size ): 
        super().__init__() 
        # autoencoder model (should be functioning on its own for train loop)
        self.autoencoder = Autoencoder(input_size) 
       
        # kmeans model 
        self.kmeans = KMeans(n_clusters=k_value, random_state= 1 )

        # fnn 
        # input size +1 for cluster feature generated by kmeans 
        self.fnn = FNN( self.autoencoder.embedding_size +1, hidden_sizes, output_size) 

    
    def forward(self, data): 
        # autoencoder embedding value 
        embedding = self.autoencoder.predict_embedding(data) # tensor 

        # kmeans cluster value 
        clusters = self.kmeans.predict(embedding.detach().numpy()) # needs array
        # note detaching means that the gradients wont flow back, which is good for fnn training 
        clusters = torch.unsqueeze(torch.from_numpy(clusters), dim = 1 )

        # combine the cluster labels to embeddings 
        embedding = torch.cat([embedding, clusters], dim =1 )

        # apply fnn 
        res= self.fnn(embedding )
        return res 

